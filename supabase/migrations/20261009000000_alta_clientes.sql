-- Alta de clientes Cafiver: perfiles, solicitudes, bitácora, almacenamiento y reglas de acceso.
-- Todas las tablas viven en el esquema public con prefijo ac_ para no chocar con otros sistemas del proyecto.

create table if not exists public.ac_perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text not null,
  email text not null,
  rol text not null default 'vendedor' check (rol in ('vendedor','jefe','admin')),
  jefe_id uuid references public.ac_perfiles(id),
  oficina text,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.ac_solicitudes (
  id uuid primary key default gen_random_uuid(),
  folio bigint generated by default as identity,
  estatus text not null default 'borrador'
    check (estatus in ('borrador','por_autorizar','autorizada','rechazada','en_sap','error_sap')),
  vendedor_id uuid not null references public.ac_perfiles(id),
  jefe_id uuid references public.ac_perfiles(id),
  oficina text,
  razon_social text,
  nombre_comercial text,
  rfc text,
  datos jsonb not null default '{}'::jsonb,          -- canal, sector, comodato, dirección fiscal, crédito, facturación
  destinatarios jsonb not null default '[]'::jsonb,  -- hasta 4 direcciones de envío
  contactos jsonb not null default '{}'::jsonb,      -- compras, pagos, operación
  productos jsonb not null default '[]'::jsonb,      -- material, UM, precio, vigencia, consumo
  csf_fecha_emision date,
  csf_data jsonb,                                    -- datos leídos de la constancia
  csf_path text,
  contrato_path text,
  motivo_rechazo text,
  num_cliente_sap text,
  destinatarios_sap jsonb,
  sap_log jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  enviada_at timestamptz,
  autorizada_at timestamptz,
  sap_at timestamptz
);
create index if not exists ac_solicitudes_vendedor_idx on public.ac_solicitudes(vendedor_id);
create index if not exists ac_solicitudes_jefe_idx on public.ac_solicitudes(jefe_id, estatus);

create table if not exists public.ac_eventos (
  id bigint generated by default as identity primary key,
  solicitud_id uuid not null references public.ac_solicitudes(id) on delete cascade,
  usuario_id uuid references public.ac_perfiles(id),
  accion text not null,
  comentario text,
  created_at timestamptz not null default now()
);

-- Funciones auxiliares (security definer evita recursión en las reglas de acceso)
create or replace function public.ac_rol() returns text
  language sql stable security definer set search_path = public as
$$ select rol from public.ac_perfiles where id = auth.uid() and activo $$;

create or replace function public.ac_es_admin() returns boolean
  language sql stable security definer set search_path = public as
$$ select coalesce(public.ac_rol() = 'admin', false) $$;

create or replace function public.ac_mi_jefe() returns uuid
  language sql stable security definer set search_path = public as
$$ select jefe_id from public.ac_perfiles where id = auth.uid() $$;

create or replace function public.ac_touch() returns trigger language plpgsql as
$$ begin new.updated_at = now(); return new; end $$;
drop trigger if exists ac_solicitudes_touch on public.ac_solicitudes;
create trigger ac_solicitudes_touch before update on public.ac_solicitudes
  for each row execute function public.ac_touch();

-- Los perfiles se dan de alta a mano (insert en ac_perfiles) para no afectar a otros sistemas del mismo proyecto.

-- Reglas de acceso
alter table public.ac_perfiles enable row level security;
alter table public.ac_solicitudes enable row level security;
alter table public.ac_eventos enable row level security;

create policy ac_perfiles_select on public.ac_perfiles for select to authenticated using (
  id = auth.uid() or id = public.ac_mi_jefe() or jefe_id = auth.uid() or public.ac_es_admin());
create policy ac_perfiles_admin on public.ac_perfiles for all to authenticated
  using (public.ac_es_admin()) with check (public.ac_es_admin());

create policy ac_sol_select on public.ac_solicitudes for select to authenticated using (
  vendedor_id = auth.uid() or jefe_id = auth.uid() or public.ac_es_admin());
create policy ac_sol_insert on public.ac_solicitudes for insert to authenticated with check (
  vendedor_id = auth.uid() and estatus = 'borrador');
create policy ac_sol_update on public.ac_solicitudes for update to authenticated
  using (vendedor_id = auth.uid() and estatus in ('borrador','rechazada'))
  with check (vendedor_id = auth.uid() and estatus in ('borrador','rechazada'));
create policy ac_sol_delete on public.ac_solicitudes for delete to authenticated using (
  vendedor_id = auth.uid() and estatus = 'borrador');

create policy ac_ev_select on public.ac_eventos for select to authenticated using (
  exists (select 1 from public.ac_solicitudes s where s.id = solicitud_id
          and (s.vendedor_id = auth.uid() or s.jefe_id = auth.uid() or public.ac_es_admin())));

-- Cambios de estatus: solo mediante estas funciones
create or replace function public.ac_enviar_a_autorizacion(p_id uuid) returns void
  language plpgsql security definer set search_path = public as
$$
declare s public.ac_solicitudes; v_jefe uuid;
begin
  select * into s from public.ac_solicitudes where id = p_id and vendedor_id = auth.uid();
  if not found then raise exception 'Solicitud no encontrada'; end if;
  if s.estatus not in ('borrador','rechazada') then raise exception 'La solicitud ya fue enviada'; end if;
  if s.csf_path is null or s.contrato_path is null then raise exception 'Faltan documentos'; end if;
  if s.csf_fecha_emision is null or s.csf_fecha_emision < current_date - 30 then
    raise exception 'La constancia fiscal no está vigente (máximo 30 días de emitida)'; end if;
  select jefe_id into v_jefe from public.ac_perfiles where id = auth.uid();
  if v_jefe is null then raise exception 'Tu usuario no tiene jefe asignado'; end if;
  update public.ac_solicitudes set estatus='por_autorizar', jefe_id=v_jefe, enviada_at=now(), motivo_rechazo=null where id=p_id;
  insert into public.ac_eventos(solicitud_id, usuario_id, accion) values (p_id, auth.uid(), 'enviada_a_autorizacion');
end $$;

create or replace function public.ac_autorizar(p_id uuid) returns void
  language plpgsql security definer set search_path = public as
$$
begin
  update public.ac_solicitudes set estatus='autorizada', autorizada_at=now()
   where id=p_id and estatus='por_autorizar' and (jefe_id=auth.uid() or public.ac_es_admin());
  if not found then raise exception 'No puedes autorizar esta solicitud'; end if;
  insert into public.ac_eventos(solicitud_id, usuario_id, accion) values (p_id, auth.uid(), 'autorizada');
end $$;

create or replace function public.ac_rechazar(p_id uuid, p_motivo text) returns void
  language plpgsql security definer set search_path = public as
$$
begin
  if coalesce(trim(p_motivo),'') = '' then raise exception 'Escribe el motivo del rechazo'; end if;
  update public.ac_solicitudes set estatus='rechazada', motivo_rechazo=p_motivo
   where id=p_id and estatus='por_autorizar' and (jefe_id=auth.uid() or public.ac_es_admin());
  if not found then raise exception 'No puedes rechazar esta solicitud'; end if;
  insert into public.ac_eventos(solicitud_id, usuario_id, accion, comentario) values (p_id, auth.uid(), 'rechazada', p_motivo);
end $$;

grant execute on function public.ac_enviar_a_autorizacion(uuid), public.ac_autorizar(uuid), public.ac_rechazar(uuid,text) to authenticated;

-- Documentos (constancia y contrato): ruta <vendedor_id>/<solicitud_id>/<archivo>
insert into storage.buckets(id, name, public) values ('ac-documentos','ac-documentos', false) on conflict (id) do nothing;

create policy ac_doc_select on storage.objects for select to authenticated using (
  bucket_id = 'ac-documentos' and (
    (storage.foldername(name))[1] = auth.uid()::text or public.ac_es_admin() or
    exists (select 1 from public.ac_solicitudes s where s.id::text = (storage.foldername(name))[2] and s.jefe_id = auth.uid())));
create policy ac_doc_insert on storage.objects for insert to authenticated with check (
  bucket_id = 'ac-documentos' and (storage.foldername(name))[1] = auth.uid()::text);
create policy ac_doc_update on storage.objects for update to authenticated using (
  bucket_id = 'ac-documentos' and (storage.foldername(name))[1] = auth.uid()::text);
